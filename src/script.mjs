// Episode 33 — "Madu 3.000 Tahun di Makam Firaun Masih Layak Dimakan."
//
// Honey from Egyptian tombs (~3,000 y, Tutankhamun's 1922 excavation; oldest
// known jars ~5,500 y from Georgia) stays edible essentially forever. Bees
// start the chemistry: nectar + enzymes + fanning until water is ~17-18%.
// Three standing defenses: (1) water activity — a supersaturated sugar
// solution that osmotically drains microbes dry; (2) acidity — pH 3-4.5 from
// gluconic acid; (3) glucose oxidase slowly releases hydrogen peroxide.
// The seal is part of the system: honey is hygroscopic, an open jar absorbs
// moisture and can ferment. Crystallization is not spoilage; browning over
// decades changes flavour, not safety. Ancient use: wound medicine (Egyptian
// medical papyri), offerings, embalming; Hippocrates prescribed honey with
// vinegar. Modern proof: medical-grade honey for hard-to-heal wounds.
//
// Sources (verified Nov 2026): National Geographic / ACS reports on edible
// tomb honey; Smithsonian on Tutankhamun finds; Georgian ~5,500 y jars;
// wound-care literature on medical-grade honey.
//
